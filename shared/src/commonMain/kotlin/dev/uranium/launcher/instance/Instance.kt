package dev.uranium.launcher.instance

import dev.uranium.launcher.core.LauncherJson
import dev.uranium.launcher.core.LauncherPaths
import dev.uranium.launcher.core.PrettyJson
import dev.uranium.launcher.core.readTextOrNull
import dev.uranium.launcher.core.writeTextAtomic
import kotlinx.serialization.Serializable
import okio.FileSystem

@Serializable
enum class LoaderType(val displayName: String, val modrinthId: String?) {
    VANILLA("Vanilla", null),
    FABRIC("Fabric", "fabric"),
    QUILT("Quilt", "quilt"),
    FORGE("Forge", "forge"),
    NEOFORGE("NeoForge", "neoforge"),
}

@Serializable
data class Instance(
    val id: String,
    val name: String,
    val mcVersion: String,
    val loader: LoaderType = LoaderType.VANILLA,
    val loaderVersion: String? = null,
    val createdAt: Long = 0,
    val lastPlayedAt: Long = 0,
    /** Per-instance overrides; null means "use the global setting". */
    val memoryMb: Int? = null,
    val jvmArgs: String? = null,
)

/** One folder per instance: `instances/<id>/instance.json` next to its own game directory. */
class InstanceStore(private val paths: LauncherPaths, private val fs: FileSystem = FileSystem.SYSTEM) {

    fun list(): List<Instance> {
        val dirs = fs.listOrNull(paths.instances) ?: return emptyList()
        return dirs.mapNotNull { dir ->
            fs.readTextOrNull(dir / "instance.json")?.let { text ->
                runCatching { LauncherJson.decodeFromString<Instance>(text) }.getOrNull()
            }
        }.sortedWith(compareByDescending<Instance> { maxOf(it.lastPlayedAt, it.createdAt) }.thenBy { it.name })
    }

    fun save(instance: Instance) {
        fs.createDirectories(paths.gameDir(instance.id))
        fs.writeTextAtomic(paths.instanceFile(instance.id), PrettyJson.encodeToString(Instance.serializer(), instance))
    }

    fun create(
        name: String,
        mcVersion: String,
        now: Long,
        loader: LoaderType = LoaderType.VANILLA,
        loaderVersion: String? = null,
    ): Instance {
        val cleanName = name.trim().ifEmpty { mcVersion }
        val instance = Instance(
            id = uniqueId(cleanName), name = cleanName, mcVersion = mcVersion,
            loader = loader, loaderVersion = loaderVersion.takeIf { loader != LoaderType.VANILLA }, createdAt = now,
        )
        save(instance)
        return instance
    }

    fun delete(id: String) {
        // Ids are generated by uniqueId(), but never let a crafted one escape the instances folder.
        require(id.isNotEmpty() && id == slug(id)) { "Invalid instance id" }
        fs.deleteRecursively(paths.instanceDir(id), mustExist = false)
    }

    private fun uniqueId(name: String): String {
        val base = slug(name).ifEmpty { "instance" }
        var candidate = base
        var n = 2
        while (fs.exists(paths.instanceDir(candidate))) candidate = "$base-${n++}"
        return candidate
    }

    companion object {
        /** Folder-safe id: lowercase ASCII letters, digits, dots and dashes only. */
        fun slug(name: String): String = name.lowercase()
            .map { c -> if (c in 'a'..'z' || c in '0'..'9' || c == '.' || c == '-') c else '-' }
            .joinToString("")
            .replace(Regex("-+"), "-")
            .trim('-', '.')
            .take(48)
    }
}
